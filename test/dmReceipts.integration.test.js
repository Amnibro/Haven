'use strict';
const test = require('node:test');
const assert = require('node:assert');
const { createHarness, wait } = require('./socketServerHarness');
const h = createHarness(3637, 'dm-receipts');
test.before(() => h.start());
test.after(() => h.stop());
test('DM receipts: sent, delivered, seen, and the off switch', async () => {
  const admin = await h.register('admin');
  const bob = await h.register('bob');
  const carol = await h.register('carol');
  const A = await h.connect(admin.token);
  const dm = await new Promise((res) => { A.once('dm-opened', (d) => res(d.code)); A.emit('start-dm', { targetUserId: bob.id }); });
  A.emit('get-channels');
  await wait(400);
  const sent = h.next(A, 'new-message', (d) => d?.message?.content === 'hi bob');
  A.emit('send-message', { code: dm, content: 'hi bob' });
  const id = (await sent).message.id;
  assert.deepStrictEqual(await h.ask(A, 'get-dm-receipt', { code: dm }), { code: dm, read: 0, delivered: 0 });
  const arrived = h.next(A, 'dm-receipt', (d) => d.code === dm && d.delivered >= id);
  const B = await h.connect(bob.token);
  assert.ok(await arrived, 'delivered once bob connects');
  B.emit('get-channels');
  await wait(300);
  const seen = h.next(A, 'dm-receipt', (d) => d.code === dm && d.read === id);
  B.emit('mark-read', { code: dm, messageId: id });
  assert.ok(await seen, 'seen once bob reads it');
  B.disconnect();
  await wait(300);
  assert.deepStrictEqual(await h.ask(A, 'get-dm-receipt', { code: dm }), { code: dm, read: id, delivered: id });
  const C = await h.connect(carol.token);
  assert.deepStrictEqual(await h.ask(C, 'get-dm-receipt', { code: dm }), { off: true });
  const B2 = await h.connect(bob.token);
  B2.emit('set-preference', { key: 'read_receipts', value: 'off' });
  await wait(300);
  assert.deepStrictEqual(await h.ask(A, 'get-dm-receipt', { code: dm }), { code: dm, off: true });
  assert.deepStrictEqual(await h.ask(B2, 'get-dm-receipt', { code: dm }), { code: dm, off: true });
  let leaked = null;
  A.on('dm-receipt', (d) => { leaked = d; });
  B2.emit('mark-read', { code: dm, messageId: id });
  await wait(400);
  assert.strictEqual(leaked, null);
  B2.emit('set-preference', { key: 'read_receipts', value: 'maybe' });
  await wait(200);
  assert.deepStrictEqual(await h.ask(A, 'get-dm-receipt', { code: dm }), { code: dm, off: true });
  for (const s of [A, B2, C]) s.disconnect();
});
